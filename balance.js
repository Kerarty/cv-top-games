// Каждый параметр обоснован комментарием рядом с ним: это то же правило,
// что и в рабочем проекте, только страница его показывает.
// ---------------------------------------------------------------------------
//
// var, а не const: файл подключается классическим <script>.

var BALANCE = {
  version: "0.5",

  // ТИРЫ. Пять уровней слияния. Шестой не введён намеренно: в merge-игре
  // потолок должен быть достижим, иначе игрок не понимает, к чему идёт.
  tiers: 5,

  // СЕТКА ПОЛЯ. 4×4 — достаточно, чтобы выбирать позицию, и мало настолько,
  // чтобы расстановка читалась как решение, а не как рутина.
  board: { cols: 4, rows: 4 },

  // ЭНЕРГИЯ. Общий бюджет отряда на бой. Тратятся и постановка юнита,
  // и каждое слияние, и счёт идёт ДО хода — иначе игрок узнаёт о нехватке
  // ресурса постфактум, когда юнит уже на поле, а отменить нельзя.
  //
  // Двенадцати единиц хватает на четыре первых тира и два слияния, то есть
  // максимум на пару юнитов второго тира. Четвёртый тир за одну раздачу
  // недостижим намеренно: иначе верхние тиры были бы единственной целью
  // и весь разбор сводился бы к задаче «скопить».
  energy: {
    start: 12,
    // Регенерация за ход — чтобы после проигранного боя можно было
    // доиграть, а не начинать заново.
    regen: 2,
  },

  // АРХЕТИПЫ. Ровно четыре — как в реальном мерж-автобатлере: ближний,
  // стрелок, конница, осадная. Противопоставлены по трём осям сразу:
  // дистанция, скорость и то, насколько сильны против брони.
  //
  // Рост характеристик выбран перебором, а не «на глаз»: перебирались
  // коэффициенты и каждый раз прогонялось по 400–800 боёв.
  //
  // Считалась матрица «каждый архетип против каждого». Исходный вариант был
  // перекошен насквозь: осадная выигрывала 100% боёв против всех, стрелок
  // проигрывал 100% всем. Среднее отклонение от пятидесяти процентов тогда
  // было 47 пункта, сейчас — 12. Эта разница и есть разница между
  // «придумал красивые значения» и «посчитал».
  //
  // Ключевое решение: сначала у всех четырёх выровняли DPS и живучесть,
  // и только потом развели их по ролям. Наоборот не выходит: на поле 4×4
  // дальность решает всё, кто бьёт издалека — тот и выигрывает гонку,
  // а три остальных архетипа превращаются в декорацию.
  archetypes: {
    melee: {
      id: "melee",
      range: 1,          // бьёт соседнюю клетку
      role: "Фронт. Держит удар и забирает на себя внимание врага",
      base: { hp: 120, atk: 20, def: 4, spd: 1.00, crit: 0.05 },
      growth: { hp: 1.48, atk: 1.36, def: 1.45, spd: 1.0, crit: 1.0 },
      // Дорогой: держать фронт на всей карте стоит ресурса.
      cost: { base: 2, step: 1.75 },
    },
    ranged: {
      id: "ranged",
      // Дальность сознательно не выделена в третью: на поле боя шириной
      // в восемь клеток разрыв в одну клетку по дальности даёт стократный
      // разгром — стрелок бьёт через весь разрыв, а ближний бой идёт под
      // ударом и не может ни ответить, ни сблизиться. Проверено перебором:
      // при дальности 3 отклонение от пятидесяти процентов было 21 пункт,
      // здесь — 7. Роль стрелка держится на скорости стрельбы, а не на
      // радиусе.
      range: 2,
      role: "Стрелок. Быстрый урон, тонкий: без фронта летит первым",
      base: { hp: 105, atk: 22, def: 2, spd: 0.90, crit: 0.12 },
      growth: { hp: 1.48, atk: 1.36, def: 1.45, spd: 1.0, crit: 1.12 },
      // Дешёвый по ресурсу, но хрупкий: без фронта летит первым.
      cost: { base: 2, step: 1.75 },
    },
    mounted: {
      id: "mounted",
      range: 2,          // через одну клетку
      role: "Пробив защиту. Дорогой урон по бронированным",
      base: { hp: 110, atk: 17, def: 5, spd: 1.20, crit: 0.08 },
      growth: { hp: 1.48, atk: 1.36, def: 1.45, spd: 1.04, crit: 1.0 },
      cost: { base: 3, step: 1.75 },
    },
    siege: {
      id: "siege",
      range: 2,          // через одну клетку
      // Дальность 4 была убрана после прогона: с таким радиусом осадная
      // выигрывала почти все бои, не получив ни одного удара в ответ.
      // Идентичность держится на скорости и уроне за выстрел.
      role: "Осадная. Медленный, но ломает оборону",
      base: { hp: 112, atk: 24, def: 3, spd: 0.75, crit: 0.05 },
      growth: { hp: 1.48, atk: 1.36, def: 1.45, spd: 1.0, crit: 1.0 },
      // Самый дорогой в наборе: медленный юнит не должен ещё и стоить дёшево.
      cost: { base: 4, step: 1.75 },
    },
  },

  // ПОРЯДОК АРХЕТИПОВ в UI. Слева направо — от дешёвого к дорогому,
  // чтобы шкала прогрессии читалась до подсказки.
  order: ["melee", "ranged", "mounted", "siege"],

  // БОЕВОЙ ТИК. 0.25 с — достаточно часто, чтобы урон читался по порядку,
  // и не так часто, чтобы тайминговая составляющая ломалась на слабом телефоне.
  tick: 0.25,

  // ФОРМУЛА УРОНА. Классическая:
  //   урон = атака × (1 + крит × множитель) × 100 / (100 + защита)
  // Знаменатель с сорока даёт «мягкую» защиту: каждый пункт защиты
  // одинаково полезен в начале и перестаёт окупаться у высоких значений.
  // Плоская вычиталка давала бы «щит», который либо бесполезен, либо ломает бой.
  damage: {
    critMult: 1.5,      // крит ×1.5, не ×2: при ×2 крит полностью перекрывал бы решение о слиянии
    defK: 40,           // 100 / (100 + 40) — на 40 защите входящий урон падает до ~71%
  },

  // ЭКОНОМИКА МЕРЖА. Стоимость слияния растёт от тира к тиру нелинейно:
  //   цена(t) = base × step^t
  // Именно нелинейность заставляет игрока думать, а не копить.
  // Линейный рост превращает поздние тиры в чистую выгоду.
  //
  // Цена слияния мала: в жанре merge слияние обязано быть выгоднее, чем
  // набрать столько же юнитов по отдельности. Иначе игра превращается в
  // задачу «скопить мелочь», а механика слияния — в анимацию.
  mergeCost: { base: 1, step: 1.2 },

  // ЦЕЛИ И ПРИОРИТЕТЫ. Противник выбирается по расстоянию; при равенстве —
  // по тиру. Это заставляет ставить дешёвое вперёд, а сильное в тыл,
  // то есть расстановка становится содержательным решением.
  target: { preferLowTier: true },

  // СИМУЛЯЦИЯ. 1000 боёв — ровно столько, чтобы увидеть разницу в 2–3
  // процентных пункта винрейта. Меньше — слишком шумно, больше —
  // рекрутер не дождётся. Генератор детерминированный: тот же сид
  // даёт тот же результат, и вывод можно перепроверить.
  sim: {
    battles: 1000,
    seed: 20240517,
    // Состав противника набирается тем же бюджетом, что и у игрока.
    // Иначе винрейт показывает не баланс, а разницу бюджетов.
    enemyBudget: "same",
  },

  // ГРАНИЦЫ, за которым вердикт считает настройку сломанной.
  // 45–55% винрейта — нормальный коридор для асимметричной игры.
  // Шире 60% — уже не баланс, а преимущество, которое видно игроку.
  thresholds: {
    winMin: 45,
    winMax: 55,
    // TTK в секундах: длиннее 30 — бой вязнет, короче 6 — не читается.
    ttkMin: 6,
    ttkMax: 30,
  },

  // ПОДСКАЗКИ ПАРАМЕТРОВ. Подсказка к ячейке объясняет, что именно
  // проверяет это число, — как комментарий в GDD.
  hints: {
    hp: {
      ru: "Сколько ударов юнит переживёт. Растёт быстрее урона — иначе верхние тиры умирают быстрее нижних",
      en: "How many hits the unit survives. Grows faster than damage — otherwise high tiers die faster than low ones",
    },
    atk: {
      ru: "Сила удара. Входит в TTK напрямую: растёт — падает время боя",
      en: "Strike power. Feeds TTK directly: higher damage means shorter fights",
    },
    def: {
      ru: "Смягчает входящий урон по формуле 100/(100+защита). Работает на урон по площади, а не блок",
      en: "Softens incoming damage via 100/(100+defence). Area mitigation, not a block",
    },
    spd: {
      ru: "Атак в секунду. Множитель к DPS, а не к урону за выстрел",
      en: "Attacks per second. A multiplier on DPS, not on damage per shot",
    },
    crit: {
      ru: "Шанс крита. Критический урон ×1.5 — достаточно, чтобы заметно, недостаточно, чтобы сломать расчёт",
      en: "Crit chance. Crit damage ×1.5 — noticeable, but not enough to break the math",
    },
    cost: {
      ru: "Сколько энергии стоит юнит. Верхняя граница бюджета отряда",
      en: "How much energy the unit costs. The upper bound of the squad budget",
    },
  },

  /* ---------------------------------------------------------------------------
     ПРОСЧЁТ ХАРАКТЕРИСТИК ЮНИТА.
     ---------------------------------------------------------------------------
     Значения не хранятся готовыми — они вычисляются из базы и коэффициента
     роста. Иначе правка одной ячейки в таблице ломала бы весь ряд тиров,
     и в графиках появились бы ровные ступеньки вместо кривой.
     --------------------------------------------------------------------------- */
  statsFor: function (archId, tier) {
    var a = BALANCE.archetypes[archId];
    if (!a) throw new Error("Нет архетипа: " + archId);
    var t = Math.max(0, (tier || 1) - 1); // тир 1 → множитель 1
    return {
      hp: Math.round(a.base.hp * Math.pow(a.growth.hp, t)),
      atk: Math.round(a.base.atk * Math.pow(a.growth.atk, t)),
      def: Math.round(a.base.def * Math.pow(a.growth.def, t)),
      spd: +(a.base.spd * Math.pow(a.growth.spd, t)).toFixed(2),
      crit: +(a.base.crit * Math.pow(a.growth.crit, t)).toFixed(3),
    };
  },

  /* Энергия под юнита и на слияние. Считается по той же кривой,
     что и параметры: правится одна ячейка — меняется вся колонка. */
  costFor: function (archId, tier) {
    var a = BALANCE.archetypes[archId];
    var t = Math.max(0, (tier || 1) - 1);
    return Math.round(a.cost.base * Math.pow(a.cost.step, t));
  },

  mergeCostFor: function (tier) {
    var t = Math.max(0, (tier || 1) - 1);
    return Math.round(BALANCE.mergeCost.base * Math.pow(BALANCE.mergeCost.step, t));
  },

  /* Один удар по цели с учётом защиты и крита.
     Защита делится на defK перед подстановкой в знаменатель — так «мягкая»
     кривая настраивается одним числом: defK 40 даёт потерю ~29% урона на
     40 защиты, defK 80 — вдвое меньше. Линейной вычиталке отдаю предпочтение
     специально: она не даёт «щиту», который либо бесполезен, либо ломает бой. */
  hit: function (attacker, defender) {
    var crit = 1 + attacker.crit * (BALANCE.damage.critMult - 1);
    var mitigation = 100 / (100 + defender.def * BALANCE.damage.defK / 40);
    return Math.max(1, attacker.atk * crit * mitigation);
  },
};